import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium, expect } from '../frontend/node_modules/@playwright/test/index.mjs';
import { build } from '../frontend/node_modules/esbuild/lib/main.js';
import { uiTestServer } from './ui-test-server.mjs';

const directory = resolve(process.argv[2]);
const fixtures = JSON.parse(await readFile(resolve(directory,'dashboard-fixtures.json')));
const widget = JSON.parse(await readFile(resolve(directory,'widget-fixture.json')));
const compiled = await build({entryPoints:['frontend/src/summary-image-data.ts'],bundle:true,format:'esm',write:false});
const {summaryImageSnapshot} = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`);
assert.equal(summaryImageSnapshot(fixtures.antigravity,false).tokens,117);
assert.equal(summaryImageSnapshot(fixtures.antigravity,false).cost,null);
assert.equal(summaryImageSnapshot(fixtures.antigravity,false).partial,true);
const server = await uiTestServer();
const browser = await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHANNEL ? {channel:process.env.PLAYWRIGHT_CHANNEL} : {})});
const errors=[],actions=[];
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',error => errors.push(error.message));
  await page.route('**/api/*',async route => {
    const name = new URL(route.request().url()).pathname.split('/').pop();
    const args = route.request().postDataJSON();
    actions.push([name,args]);
    let value = {};
    if (name==='dashboard') value = {...fixtures[args.provider || ''],filters:args};
    if (name==='status') value = {...fixtures[''].job,revision:fixtures[''].revision};
    if (name==='accounts') value = {enabled:false,allowed:false,accounts:[],login:{status:'idle'}};
    if (name==='widget_summary') value=widget;
    await route.fulfill({json:value});
  });
  await page.goto(server.url);
  await expect(page.locator('#total-tokens-kpi')).toContainText('117');
  await expect(page.locator('#total-tokens-kpi')).toContainText('partial');
  await expect(page.locator('[aria-label="Metric coverage"]')).toContainText('Cache writes: unavailable');
  await page.locator('#filter-provider').selectOption('codex');
  await expect(page.locator('#token-activity')).toHaveAttribute('data-total-tokens', '');
  await expect(page.locator('.token-empty')).toHaveText('Token counters unavailable in this range.');
  // The lifetime headline remains independent of the selected provider.
  await expect(page.locator('#total-tokens-kpi')).toContainText('117');
  await page.locator('#filter-provider').selectOption('antigravity');
  await expect(page.locator('#token-activity')).toHaveAttribute('data-total-tokens', '117');
  await page.locator('[data-page="usage"]').click();
  await expect(page.locator('.component-list').first()).toContainText('Unavailable');
  await page.locator('[data-page="projects"]').click();
  await expect(page.locator('tbody .partial-mark')).toHaveCount(1);
  await page.locator('[data-page="sources"]').click();
  await expect(page.locator('.source-card')).toContainText('Collection disabled');
  await expect(page.locator('.source-card')).toContainText('1 session segments');
  await expect(page.locator('.source-card')).toContainText('Previously indexed history is retained');
  await expect(page.locator('.source-card')).toContainText('public transcripts and official hooks');
  await expect(page.locator('.source-card .fine-print').filter({ hasText: 'Encrypted archive collection' })).toHaveCount(1);
  await page.locator('#add-source').click();
  await expect(page.locator('#source-provider option[value="antigravity_legacy"]')).toHaveCount(0);
  await expect(page.locator('#source-provider option[value="antigravity"]')).toHaveText('Antigravity (public transcripts)');
  await expect(page.locator('#legacy-add')).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.screenshot({path:resolve(directory,'legacy-sources.png'),fullPage:true});
  const report = await browser.newPage();
  report.on('pageerror',error=>errors.push(error.message));
  await report.goto(pathToFileURL(resolve(directory,'legacy-report.html')).href);
  await expect(report.locator('#total-tokens-kpi')).toContainText('partial');
  await expect(report.locator('[aria-label="Metric coverage"]')).toContainText('Cache writes: unavailable');
  await report.locator('[data-page="sources"]').click();
  await expect(report.locator('.source-card')).toContainText('Collection disabled');
  await expect(report.locator('.source-card')).toContainText('Previously indexed usage remains included.');
  await expect(report.locator('.source-card .fine-print').filter({ hasText: 'Encrypted archive collection' })).toHaveCount(1);
  await expect(report.locator('.source-card')).toContainText('Path hidden in saved report');
  await expect(report.locator('.source-card')).not.toContainText('Synthetic demo source');
  await expect(report.locator('#add-source')).toBeDisabled();
  await report.screenshot({path:resolve(directory,'legacy-report.png'),fullPage:true});
  const html = await readFile(resolve(directory,'legacy-report.html'),'utf8');
  assert(!html.includes('private-profile-location'));
  assert(!html.includes('PRIVATE_PAYLOAD_DO_NOT_EXPORT'));
  await page.goto(`${server.url}/widget/index.html`);
  await expect(page.locator('.metric-tokens')).toContainText('117*');
  await expect(page.locator('.metric-cost')).toContainText('Unpriced');
  assert(!actions.some(([name]) => ['legacy_source_preview', 'add_legacy_source'].includes(name)));
  assert.deepEqual(errors,[]);
  console.log('Retained legacy UI passed: collection disabled, public transcript setup, provider filters, nullable components, partial projects, widgets, copied-image data and offline report privacy.');
} finally {await browser.close();server.close();}
